//! The system clipboard: watching it for copied text, and putting text on it.
//!
//! Only plain text is recorded. Copies that the copying app marks as private
//! (password managers do) or as not meant for clipboard history are left
//! out, and so are copies of files.

use std::{
    sync::{
        atomic::{AtomicI64, Ordering},
        Mutex,
    },
    thread,
    time::Duration,
};

use tauri::{AppHandle, Emitter, Manager};

use crate::store::Store;

/// How often the clipboard is checked for a new copy.
const POLL: Duration = Duration::from_millis(400);

/// The change count right after Clip itself last wrote to the clipboard, so
/// that a pasted snippet doesn't end up in the history.
static OWN_CHANGE: AtomicI64 = AtomicI64::new(i64::MIN);
/// Held while writing and while checking for a new copy, so the check never
/// sees Clip's own write before [`OWN_CHANGE`] knows about it.
static LOCK: Mutex<()> = Mutex::new(());

/// Records each new copy in the history, on a background thread.
pub fn watch(app: &AppHandle) {
    let app = app.clone();
    thread::spawn(move || {
        let mut seen = on_main(&app, imp::change_count).unwrap_or_default();
        loop {
            thread::sleep(POLL);
            let copied = {
                let _guard = LOCK.lock().unwrap();
                let Some(count) = on_main(&app, imp::change_count) else { continue };
                if count == seen {
                    continue;
                }
                seen = count;
                if count == OWN_CHANGE.load(Ordering::SeqCst) {
                    continue;
                }
                on_main(&app, imp::text_for_history).flatten()
            };
            let Some(text) = copied else { continue };
            match app.state::<Store>().record(&text) {
                Ok(true) => {
                    let _ = app.emit("entries-changed", ());
                }
                Ok(false) => {}
                Err(e) => eprintln!("history: {e}"),
            }
        }
    });
}

/// Puts `text` on the clipboard as plain text. Returns false if the
/// clipboard could not be written.
pub fn write_text(app: &AppHandle, text: &str) -> bool {
    let _guard = LOCK.lock().unwrap();
    let text = text.to_string();
    let written = on_main(app, move || imp::write_text(&text)).unwrap_or(false);
    if written {
        if let Some(count) = on_main(app, imp::change_count) {
            OWN_CHANGE.store(count, Ordering::SeqCst);
        }
    }
    written
}

/// Runs `f` on the main thread, where AppKit wants the pasteboard used, and
/// waits for its result. Elsewhere `f` simply runs here.
fn on_main<T: Send + 'static>(app: &AppHandle, f: impl FnOnce() -> T + Send + 'static) -> Option<T> {
    #[cfg(target_os = "macos")]
    {
        if objc2_foundation::MainThreadMarker::new().is_some() {
            return Some(f());
        }
        let (tx, rx) = std::sync::mpsc::channel();
        app.run_on_main_thread(move || {
            let _ = tx.send(f());
        })
        .ok()?;
        rx.recv_timeout(Duration::from_secs(2)).ok()
    }
    #[cfg(not(target_os = "macos"))]
    {
        let _ = app;
        Some(f())
    }
}

#[cfg(target_os = "macos")]
mod imp {
    use objc2_app_kit::{NSPasteboard, NSPasteboardTypeFileURL, NSPasteboardTypeString};
    use objc2_foundation::NSString;

    /// Pasteboard types that mark a copy as not for clipboard history
    /// (nspasteboard.org), plus the older ones some apps still use.
    const PRIVATE_TYPES: [&str; 5] = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ];

    pub fn change_count() -> i64 {
        NSPasteboard::generalPasteboard().changeCount() as i64
    }

    pub fn text_for_history() -> Option<String> {
        let pasteboard = NSPasteboard::generalPasteboard();
        let file_url = unsafe { NSPasteboardTypeFileURL }.to_string();
        let skip = pasteboard.types().is_some_and(|types| {
            types.iter().any(|t| {
                let t = t.to_string();
                t == file_url || PRIVATE_TYPES.contains(&t.as_str())
            })
        });
        if skip {
            return None;
        }
        pasteboard.stringForType(unsafe { NSPasteboardTypeString }).map(|s| s.to_string())
    }

    pub fn write_text(text: &str) -> bool {
        let pasteboard = NSPasteboard::generalPasteboard();
        pasteboard.clearContents();
        pasteboard.setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString })
    }
}

#[cfg(windows)]
mod imp {
    use std::{ffi::c_void, iter, ptr, slice, thread, time::Duration};

    use windows_sys::Win32::{
        Foundation::GlobalFree,
        System::{
            DataExchange::{
                CloseClipboard, EmptyClipboard, GetClipboardData, GetClipboardSequenceNumber,
                IsClipboardFormatAvailable, OpenClipboard, RegisterClipboardFormatW, SetClipboardData,
            },
            Memory::{GlobalAlloc, GlobalLock, GlobalSize, GlobalUnlock, GMEM_MOVEABLE},
            Ole::{CF_HDROP, CF_UNICODETEXT},
        },
    };

    /// Closes the clipboard when dropped.
    struct Opened;

    impl Drop for Opened {
        fn drop(&mut self) {
            unsafe { CloseClipboard() };
        }
    }

    fn open() -> Option<Opened> {
        // Another app may be holding the clipboard for a moment.
        for _ in 0..5 {
            if unsafe { OpenClipboard(ptr::null_mut()) } != 0 {
                return Some(Opened);
            }
            thread::sleep(Duration::from_millis(20));
        }
        None
    }

    fn format(name: &str) -> u32 {
        let name: Vec<u16> = name.encode_utf16().chain(iter::once(0)).collect();
        unsafe { RegisterClipboardFormatW(name.as_ptr()) }
    }

    fn available(format: u32) -> bool {
        format != 0 && unsafe { IsClipboardFormatAvailable(format) } != 0
    }

    pub fn change_count() -> i64 {
        unsafe { GetClipboardSequenceNumber() as i64 }
    }

    pub fn text_for_history() -> Option<String> {
        let _opened = open()?;
        // Formats that password managers and others add to keep a copy out
        // of clipboard history (Win+V honours the same ones).
        if available(CF_HDROP as u32)
            || available(format("ExcludeClipboardContentFromMonitorProcessing"))
            || available(format("Clipboard Viewer Ignore"))
        {
            return None;
        }
        let can_include = format("CanIncludeInClipboardHistory");
        if available(can_include) {
            let allowed = with_locked(unsafe { GetClipboardData(can_include) }, |p, size| {
                size < 4 || unsafe { *(p as *const u32) } != 0
            });
            if allowed == Some(false) {
                return None;
            }
        }
        with_locked(unsafe { GetClipboardData(CF_UNICODETEXT as u32) }, |p, size| {
            let units = unsafe { slice::from_raw_parts(p as *const u16, size / 2) };
            let len = units.iter().position(|&u| u == 0).unwrap_or(units.len());
            String::from_utf16_lossy(&units[..len])
        })
    }

    /// Runs `f` on the locked memory behind a clipboard handle and its size.
    fn with_locked<T>(handle: *mut c_void, f: impl FnOnce(*const c_void, usize) -> T) -> Option<T> {
        if handle.is_null() {
            return None;
        }
        let p = unsafe { GlobalLock(handle) };
        if p.is_null() {
            return None;
        }
        let result = f(p, unsafe { GlobalSize(handle) });
        unsafe { GlobalUnlock(handle) };
        Some(result)
    }

    pub fn write_text(text: &str) -> bool {
        let units: Vec<u16> = text.encode_utf16().chain(iter::once(0)).collect();
        let Some(_opened) = open() else { return false };
        unsafe {
            if EmptyClipboard() == 0 {
                return false;
            }
            let handle = GlobalAlloc(GMEM_MOVEABLE, units.len() * 2);
            if handle.is_null() {
                return false;
            }
            let p = GlobalLock(handle) as *mut u16;
            if p.is_null() {
                GlobalFree(handle);
                return false;
            }
            ptr::copy_nonoverlapping(units.as_ptr(), p, units.len());
            GlobalUnlock(handle);
            // On success the clipboard owns the memory.
            if SetClipboardData(CF_UNICODETEXT as u32, handle).is_null() {
                GlobalFree(handle);
                return false;
            }
        }
        true
    }
}

/// Other systems (development on Linux): no clipboard.
#[cfg(not(any(target_os = "macos", windows)))]
mod imp {
    pub fn change_count() -> i64 {
        0
    }

    pub fn text_for_history() -> Option<String> {
        None
    }

    pub fn write_text(_text: &str) -> bool {
        false
    }
}
